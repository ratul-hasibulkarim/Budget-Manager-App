export type Lang = 'en' | 'bn';
const DICTS: Record<Lang, Record<TKey, string>> = { en, bn };
const BN_DIGITS = ['০', '১', '২', '৩', '৪', '৫', '৬', '৭', '৮', '৯'];

export function translate(lang: Lang, key: TKey, vars?: Record<string, string | number>): string {
  let s = DICTS[lang][key] ?? en[key];
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      let text = String(v);
      if (lang === 'bn' && typeof v === 'number') text = text.replace(/[0-9]/g, (d) => BN_DIGITS[Number(d)]!);
      s = s.split(`{${k}}`).join(text);
    }
  }
  return s;
}

/** Message for an error code from the rules engine / server. */
export function errorKey(code: string | undefined): TKey {
  const key = `err_${code}` as TKey;
  return key in en ? key : 'err_generic';
}

